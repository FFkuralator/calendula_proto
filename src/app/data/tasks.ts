export function getAcademicYearRange(ay: string): { start: Date; end: Date } {
  const base = parseInt(ay.split('-')[0]);
  return { start: new Date(base, 8, 1), end: new Date(base + 1, 7, 31) };
}

export function getCalendarYear(monthIndex: number, ay: string): number {
  const base = parseInt(ay.split('-')[0]);
  return monthIndex >= 8 ? base : base + 1;
}

